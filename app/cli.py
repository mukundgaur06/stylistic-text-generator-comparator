"""Command-line entry point: `python -m app.cli --help`."""
import argparse


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(prog="stylistic-text-generator-comparator", description="Sports journalists use this to compare text generated by a LoRA-adapted LLM with an N-gram model, both fine-tuned on specific sports commentary styles.")
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("hello", help="check that everything is wired up")
    ng = sub.add_parser("ngram", help="generate text from the n-gram model of one style")
    ng.add_argument("--style", default="cricket")
    ng.add_argument("--prompt", default="")
    ng.add_argument("--order", type=int, default=3)
    ng.add_argument("--max-tokens", type=int, default=40)
    ng.add_argument("--temperature", type=float, default=1.0)
    ng.add_argument("--seed", type=int, default=None)
    ft = sub.add_parser("finetune", help="fine-tune a LoRA adapter on one style (downloads distilgpt2 once)")
    ft.add_argument("--style", default="cricket")
    ft.add_argument("--epochs", type=int, default=10)
    ft.add_argument("--rank", type=int, default=8)
    lo = sub.add_parser("lora", help="generate text from the LoRA-adapted model of one style")
    lo.add_argument("--style", default="cricket")
    lo.add_argument("--prompt", default="")
    lo.add_argument("--max-tokens", type=int, default=40)
    lo.add_argument("--temperature", type=float, default=0.8)
    lo.add_argument("--seed", type=int, default=None)
    lo.add_argument("--base", action="store_true", help="switch the adapter off (plain distilgpt2)")
    cp = sub.add_parser("compare", help="n-gram vs LoRA-adapted LLM, side by side")
    cp.add_argument("--style", default="cricket")
    cp.add_argument("--prompt", default="")
    cp.add_argument("--samples", type=int, default=3, help="how many continuations per model")
    cp.add_argument("--max-tokens", type=int, default=40)
    cp.add_argument("--temperature", type=float, default=0.8)
    cp.add_argument("--order", type=int, default=3, help="n-gram order")
    cp.add_argument("--seed", type=int, default=0)
    args = parser.parse_args(argv)
    if args.command == "compare":
        from app.compare import run_comparison
        print(run_comparison(args.style, args.prompt, args.samples, args.seed, args.max_tokens,
                             args.temperature, args.order))
    elif args.command == "lora":
        from app.lora import generate_text, load_styled_model, set_adapter_enabled
        model, tok = load_styled_model(args.style)
        set_adapter_enabled(model, not args.base)
        print(generate_text(model, tok, args.prompt, args.max_tokens, args.temperature, seed=args.seed))
    elif args.command == "finetune":
        from app.lora import finetune_style
        res = finetune_style(args.style, args.epochs, args.rank)
        print(f"base held-out perplexity: {res['base_val_ppl']:.1f}")
        for row in res["history"]:
            print(f"epoch {row['epoch']:>2}  train loss {row['train_loss']:.3f}  held-out ppl {row['val_ppl']:.1f}")
        print(f"kept best epoch {res['best_epoch']} (held-out ppl {res['best_val_ppl']:.1f})")
        print(f"saved adapter -> {res['adapter']}")
    elif args.command == "hello":
        print("Stylistic Text Generator Comparator is ready. Open README.md for your milestones.")
    elif args.command == "ngram":
        from app.core import train_ngram
        model, val = train_ngram(args.style, args.order)
        print(model.generate(args.prompt, args.max_tokens, args.temperature, args.seed))
        print(f"\n[{args.style} {args.order}-gram | held-out perplexity {model.perplexity(val):.1f}]")


if __name__ == "__main__":
    main()
